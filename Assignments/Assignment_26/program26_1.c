void DisplayASCII()
{
    printf("number symbol hexadecimal octal\n");
    for(int iNo = 0; iNo <= 255; iNo++)
    {
        printf("%d\t%c\t%#x\t%#o\n",iNo,iNo,iNo,iNo);
    }
}

int main()
{
    DisplayASCII();

    return EXIT_SUCCESS;
}

